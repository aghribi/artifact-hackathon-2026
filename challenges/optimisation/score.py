def reference_tuner(beam, target, lattice):
    """Do nothing: hand back the reference tune, ignoring the target.

    The floor any real method has to beat.
    """
    return lattice


def random_search_tuner(beam, target, lattice, n_calls: int = 40, seed: int = 0):
    """Scale the quadrupoles and kick the correctors at random; keep the best draw.

    Deliberately weak, and deliberately cheap to understand. Tunes the magnets in S07
    and the FEA arc only — the 20-odd knobs closest to the readout screen.
    """
    rng = np.random.default_rng(seed)
    names = sorted(
        {
            e.name
            for e in lattice.partition_at(READOUT_SCREEN, mode="after")[0].elements
            if isinstance(e, (cheetah.Quadrupole, cheetah.CombinedCorrector))
            and e.name.split("_")[1] in ("s07", "fea")
        }
    )
    baseline = {n: read_tune(lattice)[n] for n in names}
    best_error, best = np.inf, baseline
    for _ in range(n_calls):
        trial = {}
        for name, properties in baseline.items():
            trial[name] = {
                prop: (
                    value * (1.0 + rng.normal(0.0, 0.05))
                    if prop == "k1"
                    else float(rng.normal(0.0, 2e-5))
                )
                for prop, value in properties.items()
            }
        apply_tune(lattice, trial)
        moments = measure(lattice, beam)
        error = np.abs(moments - target).mean() if np.isfinite(moments).all() else np.inf
        if error < best_error:
            best_error, best = error, trial
    apply_tune(lattice, best)
    return lattice


BASELINES = (reference_tuner, random_search_tuner)


def main() -> None:
    n_cases = 20  # the headline benchmark is 100; 20 keeps the self-test quick
    print(f"Scoring built-in baselines on {n_cases} cases\n")
    for tuner in BASELINES:
        print(f"--- {tuner.__name__} ---")
        report = score(tuner, n_cases=n_cases, progress=False)
        print(report, "\n")


if __name__ == "__main__":
    main()
