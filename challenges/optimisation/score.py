def _structure(segment) -> list[str]:
    return [f"{type(e).__name__}:{e.name}" for e in segment.elements]


def _fixed_features(segment) -> dict:
    """Everything a tuner is *not* allowed to touch, as plain floats."""
    fixed = {}
    for index, element in enumerate(segment.elements):
        allowed = next(
            (props for kind, props in TUNABLE.items() if isinstance(element, kind)), ()
        )
        for feature in element.defining_features:
            if feature in allowed or feature == "name":
                continue
            value = getattr(element, feature, None)
            if isinstance(value, torch.Tensor):
                fixed[(index, feature)] = tuple(
                    np.round(value.detach().flatten().numpy().astype(float), 9)
                )
    return fixed


def check_segment(returned, reference, _structure_of=None, _features_of=None) -> str | None:
    """None if the returned segment is a legal retune, else why it is not.

    `_structure_of` / `_features_of` let the scorer pass the reference's precomputed
    structure and fixed features, which otherwise get rebuilt on every case.
    """
    if not isinstance(returned, cheetah.Segment):
        return f"expected a cheetah.Segment, got {type(returned).__name__}"
    expected_structure = _structure_of if _structure_of is not None else _structure(reference)
    if _structure(returned) != expected_structure:
        return "lattice structure changed (elements added, removed, renamed or reordered)"
    expected = _features_of if _features_of is not None else _fixed_features(reference)
    actual = _fixed_features(returned)
    changed = [
        f"element {i} {returned.elements[i].name}.{feature}"
        for (i, feature), value in expected.items()
        if actual.get((i, feature)) != value
    ]
    if changed:
        shown = ", ".join(changed[:3])
        more = f" (+{len(changed) - 3} more)" if len(changed) > 3 else ""
        return f"non-tunable properties changed: {shown}{more}"
    return None


