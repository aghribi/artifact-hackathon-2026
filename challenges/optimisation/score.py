"""Score a full-lattice CLARA tuning function.

You write one function::

    def my_tuner(beam, target):
        '''beam: cheetah.ParticleBeam at the lattice entrance.
           target: np.array([mu_x, mu_y, sigma_x, sigma_y]) in metres, wanted at the
                   readout screen.
           returns: a configured cheetah.Segment.'''
        lattice = score.load_lattice()
        ...                                  # set magnets however you like
        return lattice

and hand it over::

    import score
    report = score.score(my_tuner)
    print(report)

`score()` runs your function against 100 random starting beams and 100 random targets,
tracks each beam through the lattice you hand back, measures the beam at
`CLA-FEH-DIA-SCR-01` (the FEBE hutch screen, s = 67.93 m) and reports how close you got.

Three things worth knowing before you start.

**Targets are reachable by construction.** Each one is generated by perturbing a
reference tune, tracking that beam, and reading off the moments it actually produced.
So for every case there is at least one magnet configuration that hits the target
exactly. Targets that lose the beam or land off the screen are rejected and redrawn.

**Evaluations are counted, not capped.** Every `track()` call on a lattice you got from
`load_lattice()` is counted and reported. Nothing stops you brute-forcing, but a method
that needs 10,000 simulator calls per beam would need 10,000 machine shots, so report
the number honestly — it is the figure that costs beam time.

**Only magnets may change.** The segment you return is checked against the reference:
same elements in the same order, and only quadrupole `k1`, corrector angles and
sextupole `k2` may differ. Anything else (drift lengths, cavity voltages, screen
positions) is a failed case.

**Baselines to beat.** Measured on 100 cases (20 for BO, which is slow):

    reference_tuner       173 um mean    0 evaluations   ignores the target entirely
    random_search_tuner    91 um mean   40 evaluations

Worth knowing before you reach for Bayesian optimisation: plain `gp_minimize` over the
~52 knobs upstream of the readout, on the same 40-evaluation budget, scores 93 um — no
better than random search. With fewer observations than dimensions the GP posterior
carries almost no information. BO wins comfortably on the 8-knob S04 problem in section
4 of the notebook; getting it to work at this scale means cutting the dimensionality,
warm-starting, or a trust region.

Budget roughly 0.1 s per simulator call: `random_search_tuner` takes ~8 minutes over
100 cases. Use `n_cases` to cut that down while iterating, but report the 100-case
number.

Run `python score.py` to score the built-in baselines on 20 cases.
"""

from __future__ import annotations

import inspect
import json
import time
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

import cheetah
import numpy as np
import torch

HERE = Path(__file__).parent
LATTICE_JSON = HERE / "data" / "clara" / "lattice_data" / "CLARA_cheetah.json"
REFERENCE_TUNE_JSON = HERE / "reference_tune.json"

# The lattice starts after the S01 aperture, matching the kickoff notebook.
LATTICE_START = "cla_s01_sim_aper_01"

# FEBE hutch, s = 67.93 m, 11.6 um pixels, +/- 11.2 x 6.98 mm.
#
# Be aware when reading scores: the FEA arc leaves D_x = -3.85 m of residual dispersion
# here, so with the beams this benchmark uses (1e-4 energy spread) roughly 97% of the
# horizontal spot size is dispersion. Quadrupoles move sigma_x very little, and a tuner
# that ignores horizontal focusing entirely still scores well on that component. The
# vertical plane and both centroids are properly controllable. Point this at
# `cla_s07_dia_scr_04` (s = 47.6 m, upstream of the arc) for a readout where all four
# components respond to the magnets.
READOUT_SCREEN = "cla_feh_dia_scr_01"

# What a tuner is allowed to change, per element type.
TUNABLE = {
    cheetah.Quadrupole: ("k1",),
    cheetah.CombinedCorrector: ("horizontal_angle", "vertical_angle"),
    cheetah.Sextupole: ("k2",),
}

TARGET_LABELS = ("mu_x", "mu_y", "sigma_x", "sigma_y")

# A case counts as a hit when its mean absolute error is within this fraction of the
# target spot size — scale-free, so a tight target is not easier than a loose one.
# Reported at several tolerances: one number is either 0% or 100% for most methods.
HIT_TOLERANCES = (0.50, 0.25, 0.10)

_PENALTY_UM = 1e4  # error booked against a case that fails, loses the beam, or errors


# --------------------------------------------------------------------------------- #
# lattice
# --------------------------------------------------------------------------------- #


def elements_named(segment, name):
    """All elements with this name, as a list.

    `getattr` on a Segment returns a bare element for a unique name but a *list* if the
    name appears more than once, so code that assumes one or the other breaks silently.
    The CLARA lattice used to hit this: a copy of the F6B block (`cla_feh_mag_quad_04`,
    `cla_feh_mag_hvcor_03/04`, `cla_feh_dia_bpm_02`) was duplicated between SCR-03 and
    FEC2, where the machine has only a vacuum valve. That is fixed in the lattice file
    now, but going through here keeps the harness correct if it ever comes back.
    """
    found = getattr(segment, name)
    return found if isinstance(found, list) else [found]


@lru_cache(maxsize=1)
def _lattice_template() -> cheetah.Segment:
    """Parsed once; `load_lattice` clones it. Parsing the JSON costs ~5 s."""
    segment = cheetah.Segment.from_lattice_json(str(LATTICE_JSON)).partition_at(
        LATTICE_START, mode="after"
    )[-1]
    apply_tune(segment, reference_tune())
    return segment


def load_lattice(count_evaluations: bool = True) -> cheetah.Segment:
    """A fresh copy of the CLARA lattice from the S01 aperture onwards.

    Comes set to the reference tune. `track()` calls on the returned segment are
    counted (see `evaluations_of`).
    """
    segment = _lattice_template().clone()
    if count_evaluations:
        _instrument(segment)
    return segment


@lru_cache(maxsize=1)
def reference_tune() -> dict:
    """Magnet settings captured from the real machine (see reference_tune.json)."""
    return json.loads(REFERENCE_TUNE_JSON.read_text())["elements"]


def apply_tune(segment, tune: dict) -> None:
    """Write a {element_name: {property: value}} mapping into a segment."""
    for name, properties in tune.items():
        try:
            elements = elements_named(segment, name)
        except AttributeError:
            continue  # element is downstream of a partition — nothing to set
        for element in elements:
            for prop, value in properties.items():
                setattr(element, prop, torch.tensor(float(value), dtype=torch.float32))


def read_tune(segment) -> dict:
    """Pull the tunable settings back out of a segment."""
    tune = {}
    for element in segment.elements:
        for kind, properties in TUNABLE.items():
            if isinstance(element, kind):
                tune[element.name] = {p: float(getattr(element, p)) for p in properties}
    return tune


def _instrument(segment) -> None:
    """Count track() calls on a segment and everything inside it."""
    segment._evaluations = [0]
    original = segment.track

    def counted(incoming, *args, **kwargs):
        segment._evaluations[0] += 1
        return original(incoming, *args, **kwargs)

    segment.track = counted
    # Partitioning hands back new Segments that share elements; keep the same counter so
    # tuners that cut the lattice down still get counted.
    original_partition = segment.partition_at

    def partition(*args, **kwargs):
        parts = original_partition(*args, **kwargs)
        for part in parts:
            if isinstance(part, cheetah.Segment):
                part._evaluations = segment._evaluations
                part_original = part.track

                def counted_part(incoming, *a, _o=part_original, **kw):
                    segment._evaluations[0] += 1
                    return _o(incoming, *a, **kw)

                part.track = counted_part
        return parts

    segment.partition_at = partition


def evaluations_of(segment) -> int:
    """How many times this segment (or a partition of it) has been tracked."""
    return getattr(segment, "_evaluations", [0])[0]


