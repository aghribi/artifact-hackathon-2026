def sample_beam(rng, num_particles: int = 10_000) -> cheetah.ParticleBeam:
    """A starting beam at the lattice entrance, 4.2 MeV out of the gun.

    Randomised around the example beam in section 3 of the kickoff notebook. That beam
    has a very low emittance by CLARA standards; the Cheetah model has no L01 solenoids,
    so a realistic 1 um normalised emittance with 1e-3 energy spread grows to tens of
    millimetres by FEBE and misses the screen entirely. Keeping the notebook's beam
    family keeps the scoring task well posed. See the README note on sim2real.

    Particle coordinates come from torch's global RNG, so it is seeded from `rng` and
    restored afterwards. Without that the benchmark is not reproducible: different
    particles shift the measured moments, which changes how many draws `sample_target`
    rejects, which desynchronises `rng` for every later case.
    """

    def uniform(low, high):
        return torch.tensor(float(rng.uniform(low, high)))

    torch_state = torch.get_rng_state()
    torch.manual_seed(int(rng.integers(2**31)))
    try:
        return _beam_from(num_particles, uniform)
    finally:
        torch.set_rng_state(torch_state)


def _beam_from(num_particles, uniform) -> cheetah.ParticleBeam:
    return cheetah.ParticleBeam.from_parameters(
        num_particles=num_particles,
        energy=uniform(4.0e6, 4.4e6),
        mu_x=uniform(-5e-5, 5e-5),
        mu_px=uniform(-1e-5, 1e-5),
        mu_y=uniform(-5e-5, 5e-5),
        mu_py=uniform(-1e-5, 1e-5),
        sigma_x=uniform(0.7e-5, 1.4e-5),
        sigma_px=uniform(0.7e-6, 1.4e-6),
        sigma_y=uniform(0.7e-5, 1.4e-5),
        sigma_py=uniform(0.7e-6, 1.4e-6),
        sigma_tau=torch.tensor(1e-6),
        sigma_p=torch.tensor(1e-4),
        dtype=torch.float32,
    )


def measure(segment, beam) -> np.ndarray:
    """(mu_x, mu_y, sigma_x, sigma_y) in metres at the readout screen."""
    to_screen = segment.partition_at(READOUT_SCREEN, mode="after")[0]
    out = to_screen.track(beam)
    return np.array(
        [out.mu_x.item(), out.mu_y.item(), out.sigma_x.item(), out.sigma_y.item()]
    )


def _screen_half_extent(segment) -> tuple[float, float]:
    extent = elements_named(segment, READOUT_SCREEN)[0].extent
    return float(extent[1]), float(extent[3])


# How far the target generator wanders from the reference tune. Big enough that the
# targets are a real ask, small enough that the beam usually survives to the screen.
TARGET_K1_SPREAD = 0.20  # relative, per quadrupole
TARGET_KICK_SPREAD = 2e-6  # rad, per corrector plane
TARGET_CENTROID_LIMIT = 1.5e-3  # m — keep targets near the middle of the screen


def sample_target(rng, beam, segment, max_tries: int = 25) -> np.ndarray | None:
    """A target that is reachable for this beam, by construction.

    Perturbs the reference tune, tracks, and takes whatever moments come out. Draws that
    lose the beam or land far off centre are rejected.

    The `sigma_x` targets come out over a narrower range than `sigma_y`. That is
    physics, not a bug: the FEA arc leaves `D_x = -3.85 m` of dispersion at this screen,
    so with 1e-4 energy spread the horizontal spot is ~300 um of dispersion almost
    regardless of the quadrupoles. Horizontal focusing is only weakly controllable here
    — see the note on `READOUT_SCREEN`.
    """
    reference = reference_tune()
    half_x, half_y = _screen_half_extent(segment)
    limit_x = min(TARGET_CENTROID_LIMIT, 0.9 * half_x)
    limit_y = min(TARGET_CENTROID_LIMIT, 0.9 * half_y)
    quads = sorted({e.name for e in segment.elements if isinstance(e, cheetah.Quadrupole)})
    correctors = sorted(
        {e.name for e in segment.elements if isinstance(e, cheetah.CombinedCorrector)}
    )
    for _ in range(max_tries):
        apply_tune(segment, reference)
        for name in quads:
            for element in elements_named(segment, name):
                scaled = float(element.k1) * (1.0 + rng.normal(0.0, TARGET_K1_SPREAD))
                element.k1 = torch.tensor(scaled, dtype=torch.float32)
        for name in correctors:
            for element in elements_named(segment, name):
                element.horizontal_angle = torch.tensor(
                    float(rng.normal(0.0, TARGET_KICK_SPREAD)), dtype=torch.float32
                )
                element.vertical_angle = torch.tensor(
                    float(rng.normal(0.0, TARGET_KICK_SPREAD)), dtype=torch.float32
                )
        moments = measure(segment, beam)
        apply_tune(segment, reference)
        if not np.isfinite(moments).all():
            continue
        if abs(moments[0]) > limit_x or abs(moments[1]) > limit_y:
            continue
        if moments[2] <= 0 or moments[3] <= 0:
            continue
        return moments
    return None


@lru_cache(maxsize=4)
def make_cases(n_cases: int = 100, seed: int = 0, num_particles: int = 10_000):
    """The fixed benchmark: n_cases (beam, target) pairs. Same seed, same cases."""
    rng = np.random.default_rng(seed)
    scratch = load_lattice(count_evaluations=False)
    cases = []
    while len(cases) < n_cases:
        beam = sample_beam(rng, num_particles)
        target = sample_target(rng, beam, scratch)
        if target is not None:
            cases.append((beam, target))
    return tuple(cases)


